// Twenty ridge courses as data. Each row is a compact spec; `course` expands it into the shape
// the simulation reads. Teaching 1-7, combination 8-14, mastery 15-20.
const GATE_LOW = 45,
  GATE_HIGH = 80,
  PAD_RUNOUT = 100,
  WALL_GAP = 140,
  WALL_TOP = 1500;

const deepFreeze = (value) => {
  if (value && typeof value === 'object' && !Object.isFrozen(value)) {
    Object.freeze(value);
    Object.values(value).forEach(deepFreeze);
  }
  return value;
};
const pairs = (flat) =>
  Array.from({ length: flat.length / 2 }, (_, i) => [flat[2 * i], flat[2 * i + 1]]);

function course(spec) {
  const [x0, x1, hw] = spec.pad,
    stations = pairs(spec.ground),
    padH = stations.at(-1)[1],
    xmax = x1 + WALL_GAP;
  return deepFreeze({
    name: { en: spec.name[0], zh: spec.name[1] },
    brief: { en: spec.brief[0], zh: spec.brief[1] },
    xmin: -200,
    xmax,
    half: spec.half ?? 260,
    snow: spec.snow ?? 230,
    palette: spec.palette,
    terrain: [[-200, WALL_TOP], ...stations, [x1 + PAD_RUNOUT, padH], [xmax, WALL_TOP]],
    start: { x: 0, z: 0, h: spec.start },
    gates: spec.gates.map(([x, z, h, gw, lo = GATE_LOW, hi = GATE_HIGH]) => ({
      x,
      z,
      h,
      hw: gw,
      lo,
      hi,
    })),
    zone: { x0, x1, z: spec.padZ ?? 0, hw },
    wind: (spec.wind ?? []).map(([a, b, wx, wz]) => ({ x0: a, x1: b, wx, wz })),
    ridges: (spec.ridges ?? []).map(([a, b, w, depth]) => ({ x0: a, x1: b, w, depth })),
    thermals: (spec.thermals ?? []).map(([x, z, rx, rz, w, top]) => ({ x, z, rx, rz, w, top })),
    socks: spec.socks,
  });
}

