// --- Level data ---------------------------------------------------------------------------------
// nodes: S = tidal sea (or a fixed river level when amp is 0), P = chamber with area a (m2), start
// level h, floor fl and wall top. valves connect two nodes (b = 'drain' leaves the system) and
// pumps lift water from a to b. gates sit in the wall between neighbouring nodes. Heights are metres.
export const S = (en, zh, mid, amp = 0, period = 60, phase = 0) => ({
  k: 'sea',
  name: [en, zh],
  mid,
  amp,
  period,
  phase,
});
export const P = (en, zh, a, h, fl = 0, top = 5.4, cap = 9) => ({
  k: 'pool',
  name: [en, zh],
  a,
  h,
  fl,
  top,
  cap,
});
export const V = (a, b, area = 1, sill = 0) => ({ a, b, area, sill });
export const PUMP = (a, b) => ({ a, b, pump: true, area: 1, sill: 0 });
export const B = (from, to, d) => ({ from, to, d });

